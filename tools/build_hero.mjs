#!/usr/bin/env node
/*
 * Render the homepage hero with @summit/hero and write the stylesheet it needs.
 *
 * The site has no page build, so this runs by hand and its output is committed,
 * the same way tools/build_menu.py fills the menu blocks. Two outputs:
 *
 *   index.html, between HERO:START and HERO:END: the component's own markup
 *     (renderHero), with its <img> wrapped in a <picture> so the AVIF sources
 *     stay. The component renders a single <img>.
 *   assets/css/summit-hero.css: the --summit-* tokens from site/brand.json,
 *     then the component's hero.css unchanged. style.css loads after it and
 *     maps the tokens and layout onto the Roses design.
 *
 * The component versions are pinned by commit in tools/package-lock.json.
 *
 * Run it with:  npm ci --prefix tools && node tools/build_hero.mjs
 */

import { readFileSync, writeFileSync } from "node:fs";
import { renderHero } from "@summit/hero/html";
import { toCssVariables } from "@summit/tokens";

const ROOT = new URL("../", import.meta.url);
const PAGE = new URL("index.html", ROOT);
const STYLESHEET = new URL("assets/css/summit-hero.css", ROOT);

const HERO = {
  title: "Witamy.",
  lede: "Polish American cooking, built on whatever Michigan farms have this week.",
  primaryCta: { label: "Reserve on Resy", href: "https://resy.com/cities/detroit-mi/venues/roses" },
  secondaryCta: { label: "See the menu", href: "menu.html" },
  image: {
    src: "assets/img/photos/room-counter.jpg",
    alt: "The open counter at Roses: pressed tin, a shelf of preserve jars, a round mirror, and two cooks working the line",
    width: 1600,
    height: 1060,
  },
};

// What the component's <img> has no props for: the widths from
// tools/build_images.py, AVIF first, and the LCP hint.
const SIZES = "(max-width: 640px) calc(100vw - 32px), (max-width: 1120px) calc(100vw - 48px), 1072px";
const AVIF = "assets/img/photos/room-counter@900.avif 900w, assets/img/photos/room-counter.avif 1600w";
const JPEG = "assets/img/photos/room-counter@900.jpg 900w, assets/img/photos/room-counter.jpg 1600w";

function withPicture(html) {
  const imgs = html.match(/<img class="summit-hero__media"[^>]*\/>/g) ?? [];
  if (imgs.length !== 1) fail(`expected one summit-hero__media <img> from renderHero, got ${imgs.length}`);
  const img = imgs[0].replace(
    ' decoding="async"/>',
    ` srcset="${JPEG}" sizes="${SIZES}" decoding="async" fetchpriority="high"/>`,
  );
  if (img === imgs[0]) fail("renderHero's <img> no longer ends in decoding=\"async\"; update withPicture");
  return html.replace(imgs[0], () => `<picture><source type="image/avif" srcset="${AVIF}" sizes="${SIZES}">${img}</picture>`);
}

function splice(url, marker, block) {
  const text = readFileSync(url, "utf8");
  const start = `<!-- ${marker}:START -->`;
  const end = `<!-- ${marker}:END -->`;
  const i = text.indexOf(start);
  const j = text.indexOf(end);
  if (i < 0 || j < i) fail(`index.html has no ${marker} block`);
  const next = `${text.slice(0, i)}${start}\n  ${block}\n  ${text.slice(j)}`;
  return write(url, text, next);
}

function write(url, before, after) {
  if (after === before) return false;
  writeFileSync(url, after);
  return true;
}

function fail(message) {
  process.stderr.write(`error: ${message}\n`);
  process.exit(1);
}

const heroCssUrl = import.meta.resolve("@summit/hero/hero.css");
const { version } = JSON.parse(readFileSync(new URL("../package.json", heroCssUrl), "utf8"));
const brand = JSON.parse(readFileSync(new URL("site/brand.json", ROOT), "utf8"));

const css = [
  `/* Generated by tools/build_hero.mjs. Do not edit: change site/brand.json or the`,
  `   pinned component and re-run it. --summit-* tokens from site/brand.json, then`,
  `   @summit/hero ${version}'s hero.css unchanged. Roses' mappings are in style.css. */`,
  ``,
  toCssVariables(brand),
  readFileSync(new URL(heroCssUrl), "utf8"),
].join("\n");

let previous = "";
try {
  previous = readFileSync(STYLESHEET, "utf8");
} catch {}

const changed = [];
if (splice(PAGE, "HERO", withPicture(renderHero(HERO)))) changed.push("index.html (HERO)");
if (write(STYLESHEET, previous, css)) changed.push("assets/css/summit-hero.css");
console.log(`hero: @summit/hero ${version}; ${changed.length ? `updated ${changed.join(", ")}` : "no changes"}`);
